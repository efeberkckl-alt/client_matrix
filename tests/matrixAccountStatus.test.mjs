import { transformSync } from 'esbuild';
import { diagnosticAccountAlias } from './helpers/kernelNavigationHarness.mjs';

const read = file => fs.readFileSync(new URL(file, import.meta.url), 'utf8');
test('cleanup cannot erase a pause or binding conflict; confirmed login can restore an account', () => {
  const source = read('../src/main/libs/matrix/accountManager.ts');
  const ast = ts.createSourceFile('accounts.ts', source, ts.ScriptTarget.Latest, true);
  const names = ['setAccountStatus', 'markAccountAlive', 'resetRunningToIdle', 'markAccountRecovery', 'markAccountCooldown', 'markAccountChargeUncertain', 'resolveAccountChargeUncertain', 'markManualDisconnect', 'clearAccountIdentity', 'forbiddenIdentitySubject', 'accountSubject'];
  const functions = ast.statements.filter(n => ts.isFunctionDeclaration(n) && names.includes(n.name?.text)).map(n => n.getText(ast).replace(/^export /, '')).join('\n');
  const accounts = [{ id: 'a', status: 'limited', statusReason: 'HTTP 403' }, { id: 'b', status: 'login_required', bindingConflict: true }];
  const logs = [], states = [];
  let now = Date.now();
  const context = vm.createContext({ getAccount: id => accounts.find(a => a.id === id), loadAccounts: () => accounts, Date: { now: () => now },
    persist() { states.push(structuredClone(accounts)); },
    persistIdentityChange(change) { if (change()) states.push(structuredClone(accounts)); }, recoveryDelay: () => 60000, coworkLog: (...args) => logs.push(args),
    _accountSSEBroadcast: null, cache: accounts, diagnosticAccountAlias });
  vm.runInContext(transformSync(functions, { loader: 'ts' }).code, context);
  context.setAccountStatus('a', 'idle');
  assert.equal(accounts[0].status, 'limited');
  context.markAccountAlive('a');
  assert.equal(accounts[0].status, 'limited'); // Login evidence cannot erase a platform restriction.
  accounts[0].status = 'running';
  context.markAccountRecovery('a', 'network_error');
  assert.equal(accounts[0].status, 'limited');
  assert.ok(accounts[0].recovery.nextCheckAt > Date.now());
  context.markAccountAlive('a');
  assert.equal(accounts[0].status, 'idle');
  assert.equal(accounts[0].statusReason, undefined);
  context.setAccountStatus('b', 'running');
  context.markAccountAlive('b');
  assert.equal(accounts[1].status, 'login_required');
  assert.equal(accounts[1].lastAliveAt, undefined);
  accounts[0].status = 'running';
  context.resetRunningToIdle();
  assert.equal(accounts[0].status, 'limited');
  assert.match(accounts[0].statusReason, /中断/);
  assert.ok(accounts[0].recovery);
  for (const reason of ['HTTP 403:平台拒绝访问', '验证码需人工处理']) {
    accounts[0].status = 'running'; delete accounts[0].recovery;
    context.markAccountChargeUncertain('a', { action: 'comment', platform: 'tiktok', at: Date.now() });
    context.setAccountStatus('a', 'limited', reason);
    context.resolveAccountChargeUncertain('a');
    context.markAccountAlive('a');
    assert.equal(accounts[0].status, 'limited');
    assert.equal(accounts[0].statusReason, reason);
    assert.equal(accounts[0].recovery, undefined);
    context.markAccountChargeUncertain('a', { action: 'comment', platform: 'tiktok', at: Date.now() });
    context.resolveAccountChargeUncertain('a');
    assert.equal(accounts[0].statusReason, reason);
    assert.equal(accounts[0].recovery, undefined);
  }
  accounts[0].status = 'running';
  context.markAccountChargeUncertain('a', { action: 'comment', platform: 'tiktok', at: Date.now() });
  context.markAccountAlive('a');
  context.setAccountStatus('a', 'idle', '');
  assert.equal(accounts[0].status, 'limited');
  assert.ok(accounts[0].chargeUncertain);
  assert.equal(accounts[0].recovery, undefined);
  context.resolveAccountChargeUncertain('a');
  assert.equal(accounts[0].chargeUncertain, undefined);
  assert.ok(accounts[0].recovery);
  const until = Date.now() + 3600_000;
  const statesBefore = states.length;
  context.markAccountCooldown('a', until);
  assert.equal(states.length, statesBefore + 1, 'cooldown and status are persisted together');
  assert.equal(states.at(-1)[0].recovery.nextCheckAt, until);
  context.markAccountCooldown('a', until - 120_000);
  context.markAccountAlive('a');
  context.setAccountStatus('a', 'idle', '');
  context.setAccountStatus('a', 'login_required');
  context.markAccountRecovery('a', 'network_error');
  assert.equal(states.length, statesBefore + 1, 'stale results cannot overwrite the newer cooldown');
  assert.equal(accounts[0].recovery.nextCheckAt, until);
  assert.equal(accounts[0].status, 'limited');
  const legacyGroup = JSON.parse('{"id":"group-only","status":"limited","statusReason":"🛑 同组多个账号受限，停止自动操作，请检查平台提示。"}');
  const hard = { id: 'own-refusal', status: 'limited', statusReason: '平台拒绝访问' };
  accounts.push(legacyGroup, hard);
  context.markAccountCooldown(legacyGroup.id, until);
  assert.equal(legacyGroup.recovery.nextCheckAt, until);
  context.markAccountCooldown(hard.id, until);
  context.setAccountStatus(hard.id, 'limited', '同一出口/代理入口的多个账号受限，暂停该组自动任务');
  context.setAccountStatus(hard.id, 'idle', '', undefined, 'connect');
  assert.deepEqual(hard, { id: 'own-refusal', status: 'limited', statusReason: '平台拒绝访问' });
  accounts[0].boundUid = 'fixture-uid';
  context.markManualDisconnect('a');
  assert.deepEqual([accounts[0].status, accounts[0].manualDisconnect, accounts[0].boundUid, accounts[0].recovery.nextCheckAt], ['login_required', true, undefined, until]);
  context.setAccountStatus('a', 'idle', '', undefined, 'connect');
  assert.equal(accounts[0].status, 'login_required', 'explicit reconnect cannot clear a live cooldown');
  context.markAccountChargeUncertain('a', { action: 'comment', platform: 'tiktok', at: now });
  assert.equal(states.at(-1)[0].chargeUncertain.at, now);
  assert.equal(states.at(-1)[0].status, 'login_required');
  context.resolveAccountChargeUncertain('a');
  assert.equal(states.at(-1)[0].recovery.nextCheckAt, until);
  accounts[0].status = 'running'; // An older persisted state left a stale running flag.
  context.resetRunningToIdle();
  assert.equal(accounts[0].status, 'login_required');
  assert.equal(accounts[0].recovery.nextCheckAt, until);
  now = until + 1;
  context.markAccountAlive('a');
  context.setAccountStatus('a', 'idle', '');
  assert.equal(accounts[0].manualDisconnect, true, 'background confirmation cannot undo an explicit disconnect');
  context.setAccountStatus('a', 'idle', '', undefined, 'connect');
  assert.equal(accounts[0].status, 'idle');
  assert.equal(accounts[0].manualDisconnect, undefined);
  assert.ok(logs.length);
});

test('both account views share conflict/pause labels and distinguish proxy endpoint from observed exit', () => {
  const source = read('../src/renderer/components/matrix/MatrixView.tsx');
  const ast = ts.createSourceFile('view.tsx', source, ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX);
  const names = ['accountExpired', 'accountStatusText', 'proxyObservationText', 'proxyObservationTitle'];
  const declarations = ast.statements.filter(n => ts.isVariableStatement(n) && n.declarationList.declarations.some(d => names.includes(d.name.getText(ast))));
  const context = vm.createContext({ i18nService: { currentLanguage: 'zh', t: k => k }, statusLabel: s => s });
  vm.runInContext(transformSync(declarations.map(n => n.getText(ast).replace(/^const /, 'var ')).join('\n'), { loader: 'ts' }).code, context);
  const conflict = { status: 'login_required', bindingConflict: true, nickname: 'kept' };
  assert.equal(context.accountExpired(conflict), false);
  assert.equal(context.accountStatusText(conflict), '绑定冲突');
  assert.match(context.accountStatusText({ status: 'limited', statusReason: 'check' }), /待检查/);
  const a = { proxy: { host: 'gateway.invalid', port: 8668, health: 'ok' } };
  assert.equal(context.proxyObservationText(a), '代理已配置');
  assert.match(context.proxyObservationTitle(a), /不代表平台登录正常/);
  a.proxy.exitIp = '192.0.2.10'; a.proxy.exitIpObservedAt = 1;
  assert.match(context.proxyObservationText(a), /192\.0\.2\.10/);
  assert.equal((source.match(/= accountStatusText\(a\)/g) || []).length, 2);
  assert.equal((source.match(/proxyObservationText\(a\)/g) || []).length, 2);
});
